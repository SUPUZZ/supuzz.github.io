// Keep the homepage focused on one brand story and one practical play idea.
const fs = require('fs');
const path = require('path');
const { decodeHTML } = require('entities');
const { blogCardInclude, withBlogCardStyles } = require('./blog-card');
const root = path.resolve(__dirname, '..');
const translations = require('../resource/homepage-locales.json');
const posts = require('../resource/home-posts-en.json');
const categories = { 'play-ideas':'Play ideas', 'product-guides':'Product guides', 'gifts-family':'Gifts & family', 'our-story':'Our story' };
const featuredFiles = [
  'article-how-supuzz-designs-building-toys.html',
  'coral-reef-building-toy-play-ideas.html'
];
const escape = value => String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const items = featuredFiles.map(file => {
  const post = posts.find(post => post.file === file);
  if (!post) throw new Error(`Missing featured homepage post: ${file}`);
  if (!categories[post.category] || !/^[\w-]+\.html$/.test(post.file)) throw new Error(`Invalid homepage post: ${post.file}`);
  if (!fs.existsSync(path.join(root, 'static', post.image))) throw new Error(`Missing post image: ${post.image}`);
  if (!fs.existsSync(path.join(root, 'en', post.file))) throw new Error(`Missing featured article: ${post.file}`);
  return post;
});
if (new Set(items.map(post => post.file)).size !== items.length) throw new Error('Duplicate homepage posts');
for (const directory of ['en', ...Object.keys(translations)]) {
const copy = translations[directory]?.journal || {
  eyebrow:'OUR WORLD', title:'Inside SUPUZZ.', intro:'Meet the ideas behind our toys, and discover new ways to play.',
  all:'Explore all articles', story:'Our story', play:'Play ideas'
};
const localizedItems = items.map(post => {
  if (directory === 'en') return post;
  const article = fs.readFileSync(path.join(root, directory, post.file), 'utf8');
  const excerpt = article.match(/<meta name="description"\s+content="([^"]*)"/)[1];
  const story = post.category === 'our-story';
  const { image, width, height } = post;
  if (!fs.existsSync(path.join(root, 'static', image))) throw new Error(`Missing localized cover: ${directory}/${image}`);
  return {...post, image, width, height, excerpt:decodeHTML(excerpt), title:story ? copy.storyTitle : copy.playTitle, alt:story ? copy.storyAlt : copy.playAlt};
});
const cards = localizedItems.map(post => blogCardInclude({
  href:post.file, category:post.category, image:post.image, width:post.width, height:post.height,
  alt:post.alt, title:post.title, excerpt:post.excerpt,
  categoryLabel:post.category === 'our-story' ? copy.story : copy.play
})).join('\n');
const section = `    <!-- Homepage journal: generated by scripts/build-home-journal.js -->
    <section class="home-journal" id="journal" aria-labelledby="journal-title">
        <div class="container">
            <div class="journal-heading"><div><p class="home-eyebrow">${escape(copy.eyebrow)}</p><h2 id="journal-title">${escape(copy.title)}</h2><p class="journal-intro">${escape(copy.intro)}</p></div><a class="journal-all" href="blog.html">${escape(copy.all)} <span aria-hidden="true">↗</span></a></div>
            <div class="journal-grid" id="home-blog-grid">
${cards}
            </div>
        </div>
    </section>
    <!-- End homepage journal -->`;
const homePath = path.join(root,directory,'index.html');
let home = fs.readFileSync(homePath,'utf8');
const generated = /    <!-- Homepage journal: generated[^\n]* -->[\s\S]*?<!-- End homepage journal -->/;
if (generated.test(home)) home = home.replace(generated,section);
else {
  const start = home.indexOf('    <div class="container" id="journal">');
  const end = home.indexOf('    <include src="components/footer.html">',start);
  if (start < 0 || end < 0) throw new Error('Homepage journal marker not found');
  home = home.slice(0,start) + section + '\n\n' + home.slice(end);
}
fs.writeFileSync(homePath,withBlogCardStyles(home));
console.log(`Rendered ${items.length} curated homepage stories for ${directory}.`);
}
