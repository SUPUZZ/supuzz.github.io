const fs = require('node:fs');
const path = require('node:path');

function render(english) {
  if (!/<head>/i.test(english) || /<base\b/i.test(english)) {
    throw new Error('Expected the English homepage with no existing base URL');
  }
  // Resolve shared navigation, cards, static assets and inline module imports
  // exactly as on /en/index.html, while serving the document at the root URL.
  const newline = english.includes('\r\n') ? '\r\n' : '\n';
  return `<!-- Generated by scripts/build-root-homepage.js from en/index.html. Do not edit directly. -->${newline}`
    + english.replace(/<head>/i, `<head>${newline}    <base href="/en/">`);
}

function run(baseDir = path.resolve(__dirname, '..')) {
  const english = fs.readFileSync(path.join(baseDir, 'en', 'index.html'), 'utf8');
  fs.writeFileSync(path.join(baseDir, 'index.html'), render(english));
  console.log('Generated the root homepage from the English homepage without a redirect.');
}

if (require.main === module) run();
module.exports = { render, run };
